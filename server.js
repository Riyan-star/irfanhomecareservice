/* ---------- Settings (from .env or the environment) ---------- */
const envPath = path.join(__dirname, ".env");
if (fs.existsSync(envPath)) {
  for (const line of fs.readFileSync(envPath, "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (m && !(m[1] in process.env)) {
      process.env[m[1]] = m[2].replace(/^["']|["']$/g, "");
    }
  }
}

const PORT = Number(process.env.PORT) || 3000;
const ADMIN_USER = process.env.ADMIN_USER || "admin";
const ADMIN_PASSWORD = process.env.ADMIN_PASSWORD || "";

if (ADMIN_PASSWORD.length < 8) {
  console.error(
    "\nSet ADMIN_PASSWORD (at least 8 characters) in a .env file before starting.\n" +
      "Copy .env.example to .env and edit it.\n"
  );
  process.exit(1);
}

/* ---------- Storage ---------- */
const DATA_DIR = path.join(__dirname, "data");
const DB_FILE = path.join(DATA_DIR, "db.json");
const DATABASE_URL = process.env.DATABASE_URL;
let pool;
let db;
fs.mkdirSync(DATA_DIR, { recursive: true });

function freshDb() {
  return {
    nextRequestId: 1,
    nextDoctorId: 2,
    doctors: [{ id: 1, name: "Dr. Ibrahim", phone: "0728790921", available: true }],
    requests: [],
  };
}

function saveDb() {
  const tmp = DB_FILE + ".tmp";
  fs.writeFileSync(tmp, JSON.stringify(db, null, 2));
  fs.renameSync(tmp, DB_FILE);
}

async function initStorage() {
  if (!DATABASE_URL) {
    if (process.env.NODE_ENV === "production") {
      throw new Error("DATABASE_URL is required in production.");
    }
    try {
      db = JSON.parse(fs.readFileSync(DB_FILE, "utf8"));
    } catch {
      db = freshDb();
      saveDb();
    }
    return;
  }

  pool = new Pool({ connectionString: DATABASE_URL });
  await pool.query(`
    CREATE TABLE IF NOT EXISTS doctors (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      phone TEXT NOT NULL DEFAULT '',
      available BOOLEAN NOT NULL DEFAULT TRUE
    );
    CREATE TABLE IF NOT EXISTS requests (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      name TEXT NOT NULL,
      phone TEXT NOT NULL,
      area TEXT NOT NULL,
      who TEXT NOT NULL,
      need TEXT NOT NULL,
      details TEXT NOT NULL DEFAULT '',
      status TEXT NOT NULL DEFAULT 'new',
      doctor_id BIGINT REFERENCES doctors(id) ON DELETE SET NULL,
      visit TEXT NOT NULL DEFAULT ''
    );
  `);
  await pool.query(
    `INSERT INTO doctors (name, phone, available)
     SELECT $1, $2, TRUE WHERE NOT EXISTS (SELECT 1 FROM doctors)`,
    ["Dr. Ibrahim", "0728790921"]
  );
}

const doctorFromRow = (row) => ({
  id: Number(row.id),
  name: row.name,
  phone: row.phone,
  available: row.available,
});

const requestFromRow = (row) => ({
  id: Number(row.id),
  createdAt: new Date(row.created_at).toISOString(),
  name: row.name,
  phone: row.phone,
  area: row.area,
  who: row.who,
  need: row.need,
  details: row.details,
  status: row.status,
  doctorId: row.doctor_id === null ? null : Number(row.doctor_id),
  visit: row.visit,
});

async function listRequests() {
  if (!pool) return [...db.requests].reverse();
  const { rows } = await pool.query("SELECT * FROM requests ORDER BY id DESC");
  return rows.map(requestFromRow);
}

async function listDoctors() {
  if (!pool) return db.doctors;
  const { rows } = await pool.query("SELECT * FROM doctors ORDER BY id");
  return rows.map(doctorFromRow);
}

async function getRequest(id) {
  if (!pool) return db.requests.find((request) => request.id === id);
  const { rows } = await pool.query("SELECT * FROM requests WHERE id = $1", [id]);
  return rows[0] ? requestFromRow(rows[0]) : undefined;
}

async function getDoctor(id) {
  if (!pool) return db.doctors.find((doctor) => doctor.id === id);
  const { rows } = await pool.query("SELECT * FROM doctors WHERE id = $1", [id]);
  return rows[0] ? doctorFromRow(rows[0]) : undefined;
}

async function persistRequest(request) {
  if (!pool) {
    saveDb();
    return request;
  }
  const { rows } = await pool.query(
    `UPDATE requests SET doctor_id = $1, visit = $2, status = $3
     WHERE id = $4 RETURNING *`,
    [request.doctorId, request.visit, request.status, request.id]
  );
  return requestFromRow(rows[0]);
}

async function createRequest(data) {
  if (!pool) {
    const request = {
      id: db.nextRequestId++,
      createdAt: new Date().toISOString(),
      ...data,
    };
    db.requests.push(request);
    saveDb();
    return request;
  }
  const { rows } = await pool.query(
    `INSERT INTO requests (name, phone, area, who, need, details)
     VALUES ($1, $2, $3, $4, $5, $6) RETURNING *`,
    [data.name, data.phone, data.area, data.who, data.need, data.details]
  );
  return requestFromRow(rows[0]);
}

async function createDoctor(name, phone) {
  if (!pool) {
    const doctor = { id: db.nextDoctorId++, name, phone, available: true };
    db.doctors.push(doctor);
    saveDb();
    return doctor;
  }
  const { rows } = await pool.query(
    "INSERT INTO doctors (name, phone) VALUES ($1, $2) RETURNING *",
    [name, phone]
  );
  return doctorFromRow(rows[0]);
}

async function setDoctorAvailability(id, available) {
  if (!pool) {
    const doctor = db.doctors.find((item) => item.id === id);
    if (!doctor) return undefined;
    doctor.available = available;
    saveDb();
    return doctor;
  }
  const { rows } = await pool.query(
    "UPDATE doctors SET available = $1 WHERE id = $2 RETURNING *",
    [available, id]
  );
  return rows[0] ? doctorFromRow(rows[0]) : undefined;
}

async function deleteDoctor(id) {
  if (!pool) {
    db.doctors = db.doctors.filter((doctor) => doctor.id !== id);
    for (const request of db.requests) {
      if (request.doctorId === id) {
        request.doctorId = null;
        if (request.status === "assigned") request.status = "new";
      }
    }
    saveDb();
    return;
  }
  const client = await pool.connect();
  try {
    await client.query("BEGIN");
    await client.query(
      `UPDATE requests SET doctor_id = NULL, status = 'new'
       WHERE doctor_id = $1 AND status = 'assigned'`,
      [id]
    );
    await client.query("DELETE FROM doctors WHERE id = $1", [id]);
    await client.query("COMMIT");
  } catch (error) {
    await client.query("ROLLBACK");
    throw error;
  } finally {
    client.release();
  }
}

const asyncRoute = (handler) => (req, res, next) =>
  Promise.resolve(handler(req, res, next)).catch(next);

/* ---------- Helpers ---------- */
const WHO = ["a child", "an adult", "an older person"];
const NEED = [
  "daily special needs care",
  "home nursing",
  "care after surgery",
  "advice on what care is needed",
];
const STATUSES = ["new", "assigned", "done", "cancelled"];

const clean = (value, max) =>
  String(value ?? "").replace(/[\u0000-\u001f\u007f]/g, " ").trim().slice(0, max);

const sha = (s) => crypto.createHash("sha256").update(String(s)).digest();

function adminAuth(req, res, next) {
  const header = req.headers.authorization || "";
  if (header.startsWith("Basic ")) {
    const decoded = Buffer.from(header.slice(6), "base64").toString();
    const i = decoded.indexOf(":");
    const user = decoded.slice(0, i);
    const pass = decoded.slice(i + 1);
    const okUser = crypto.timingSafeEqual(sha(user), sha(ADMIN_USER));
    const okPass = crypto.timingSafeEqual(sha(pass), sha(ADMIN_PASSWORD));
    if (okUser && okPass) return next();
  }
  res
    .set("WWW-Authenticate", 'Basic realm="Irfan coordinator", charset="UTF-8"')
    .status(401)
    .send("Login required");
}

// Allow at most 5 public requests per IP every 10 minutes.
const hits = new Map();
function limitPublic(req, res, next) {
  const now = Date.now();
  const windowMs = 10 * 60 * 1000;
  const list = (hits.get(req.ip) || []).filter((t) => now - t < windowMs);
  if (list.length >= 5) {
    return res.status(429).json({
      error: "Too many requests. Please call 0728790921 if this is urgent.",
    });
  }
  list.push(now);
  hits.set(req.ip, list);
  next();
}
setInterval(() => {
  const now = Date.now();
  for (const [ip, list] of hits) {
    if (!list.some((t) => now - t < 10 * 60 * 1000)) hits.delete(ip);
  }
}, 30 * 60 * 1000).unref();

